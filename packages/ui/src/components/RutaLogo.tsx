/**
 * Marca RUTA.
 *
 * Los trazos vienen de `docs-ruta/branding/` (los SVG vectorizados originales).
 * Dos ajustes sobre la fuente, a propósito:
 *
 * 1. **`viewBox` recortado al contenido.** Los originales son lienzos de
 *    2000x2000 con el logo centrado y mucho aire alrededor; usados tal cual el
 *    logo se ve diminuto dentro de su caja. Aquí el `viewBox` se ciñe al
 *    recuadro real de la tinta (calculado desde los trazos) más un 1.5% de aire.
 * 2. **Un solo color.** El logo completo original trae el "by ORKO" en
 *    `#FF0000`: un residuo de la vectorización, no una decisión de marca — en el
 *    PNG de referencia ese texto es naranja. Todo usa `currentColor`, así que el
 *    color lo decide quien lo monta, vía `className`.
 */

interface LogoProps {
  /** Clases de tamaño y color. El trazo hereda `currentColor`. */
  className?: string
  /** Texto accesible. `null` lo vuelve decorativo, cuando ya hay un rótulo al lado. */
  title?: string | null
}

